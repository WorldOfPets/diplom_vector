                'average' => 'Основные эмоции узнаёте, но смешанные состояния и маскировку читаете не всегда. Помогут сцены с контекстом.',
                'below_average' => 'Вы часто опираетесь на первое впечатление и пропускаете контекст. Начните с колеса эмоций и карты тела.',
