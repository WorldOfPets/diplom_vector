                'average' => 'Связь «ситуация → эмоция» видите, но сложные смеси пока путаются. Полезны кейсы с двумя эмоциями.',
                'below_average' => 'Причины эмоций часто сводятся к «просто плохо». Помогут разборы ситуаций и вопросы «что именно я потерял/не получил».',
                'low' => 'Эмоции кажутся «просто плохими» или «просто хорошими». Начните с различий между страхом, тревогой и злостью.',
            ],
            EiBranch::Using->value => [
                'high' => 'Вы умеете использовать состояние под задачу, а не бороться с ним.',
                'above_average' => 'Вы умеете использовать состояние под задачу. Тренируйте устойчивость в стрессе.',
