    private function createTest(array $attributes): Test
    {
        $test = Test::query()->updateOrCreate(['slug' => $attributes['slug']], $attributes);
        $test->items()->delete();

        return $test;
    }

    private function addItem(Test $test, array $data): void
    {
        static $sorts = [];

        $testId = $test->id;
        $sorts[$testId] = ($sorts[$testId] ?? 0) + 1;

        $test->items()->create([
            ...$data,
            'sort' => $sorts[$testId],
            'weight' => $data['weight'] ?? 1,
            'difficulty' => $data['difficulty'] ?? 2,
            'is_active' => true,
        ]);
    }

    private function textOptions(array $labels): array
    {
        return collect($labels)
            ->values()
            ->map(fn (string $label, int $index): array => ['id' => 'o'.($index + 1), 'label' => $label])
            ->all();
    }

