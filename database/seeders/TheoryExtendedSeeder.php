## Упражнение «три слова»

Когда чувствуете, что «накрывает»:

1. Назовите первое слово, которое приходит.
2. Добавьте ещё два слова, которые тоже могут быть правдой.
3. Выберите, какое из них ближе всего к телу и ситуации.
4. Спросите: «Какую потребность или границу это подсвечивает?»

Пример: «бесит» → «раздражение», «обида», «усталость». Ближе всего — «обида»: я ждал поддержки, а получил оценку. Действие уже другое: не атаковать, а сказать, что мне нужна поддержка.

