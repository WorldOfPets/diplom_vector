## Зачем вообще вести дневник

Дневник эмоций — это не отчёт для куратора и не способ «стать удобным». Это короткая практика, которая тренирует три вещи:

1. **Замечать сигнал** — тело, мысли, импульс, ситуацию.
2. **Называть точнее** — не «плохо», а «тревога», «обида», «раздражение», «разочарование».
3. **Выбирать действие** — что я сделаю с этим состоянием, а не что оно сделает со мной.

Эмоциональный интеллект начинается не с контроля, а с различения. Пока состояние называется «как-то плохо», выбрать реакцию почти невозможно: непонятно, что именно регулировать.

## Что происходит, когда мы называем чувство

В исследовании Lieberman и коллег (2007) участники смотрели на эмоциональные изображения и называли чувства словами. При названии снижалась активность миндалины — области, связанной с быстрой реакцией на угрозу, — и усиливалась активность префронтальных зон, отвечающих за осмысление.

Это не значит, что одно слово «выключает» эмоцию. Это значит, что **называние переводит переживание из режима «действуй немедленно» в режим «посмотрим, что происходит»**.

Письменная практика тоже изучена: экспрессивное письмо (Pennebaker) помогает структурировать опыт, если человек пишет о переживании и его смысле, а не просто повторяет боль. Поэтому в дневнике важны не только «что я чувствую», но и «что это значит» и «что я могу сделать».

